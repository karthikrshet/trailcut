MakeCas = Callable[..., dict[str, Any]]


def make_pdf(text: str) -> bytes:
    """Build a minimal, valid one-page PDF with the given text, in memory."""
    stream = f"BT /F1 12 Tf 72 720 Td ({text}) Tj ET".encode("latin-1")
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
        b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out = io.BytesIO()
    out.write(b"%PDF-1.4\n")
    offsets = []
    for i, body in enumerate(objects, start=1):
        offsets.append(out.tell())
        out.write(b"%d 0 obj\n" % i + body + b"\nendobj\n")
    xref = out.tell()
    out.write(b"xref\n0 %d\n0000000000 65535 f \n" % (len(objects) + 1))
    for off in offsets:
        out.write(b"%010d 00000 n \n" % off)
    out.write(
        b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objects) + 1, xref)
    )
    return out.getvalue()


PDF = make_pdf("Consolidated Account Statement")


def returning(result: Any) -> Callable[[io.BytesIO, str], Any]:
    def parser(stream: io.BytesIO, password: str) -> Any:
        assert stream.read(5) == b"%PDF-"
        return result

    return parser


def raising(exc: Exception) -> Callable[[io.BytesIO, str], Any]:
    def parser(stream: io.BytesIO, password: str) -> Any:
        raise exc

    return parser


# ---------- upload guard ----------


@pytest.mark.parametrize(
    ("data", "error"),
    [
        (b"", EmptyFileError),
        (bytearray(), EmptyFileError),
        (b"hello world", NotAPdfError),
        (b"PK\x03\x04 zip file", NotAPdfError),
        (b"\x89PNG\r\n", NotAPdfError),
        (b"%PDF" + b"x" * 10, NotAPdfError),
        (b"x" * 2000 + b"%PDF-1.7", NotAPdfError),
    ],
)
def test_check_upload_rejects(data: bytes, error: type[IngestError]) -> None:
    with pytest.raises(error):
        check_upload(data)


@pytest.mark.parametrize("size", [MAX_PDF_BYTES, MAX_PDF_BYTES + 1])
def test_check_upload_rejects_10mb_or_more(size: int) -> None:
    with pytest.raises(FileTooLargeError):
        check_upload(b"%PDF-" + b"0" * (size - 5))


@pytest.mark.parametrize(
    "data", [PDF, b"%PDF-1.7\n", b"\xef\xbb\xbf%PDF-1.4", b"junk" * 10 + b"%PDF-1.5"]
)
def test_check_upload_accepts_pdfs(data: bytes) -> None:
    check_upload(data)


def test_just_under_limit_is_accepted() -> None:
    check_upload(b"%PDF-" + b"0" * (MAX_PDF_BYTES - 6))


