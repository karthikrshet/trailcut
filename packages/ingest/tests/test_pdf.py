# ---------- parse_cas_pdf ----------


def test_parses_through_injected_parser(make_cas: MakeCas) -> None:
    p = parse_cas_pdf(PDF, "secret", parser=returning(make_cas()))
    assert p.source is StatementSource.CAMS
    assert p.schemes[0].scheme_id == "F1-S1"


def test_accepts_casparser_model_result(make_cas: MakeCas) -> None:
    model = CASData.model_validate(make_cas())
    assert parse_cas_pdf(PDF, "pw", parser=returning(model)).folios[0].folio_id == "F1"


def test_password_is_passed_as_plain_string(make_cas: MakeCas) -> None:
    seen: list[str] = []

    def parser(stream: io.BytesIO, password: str) -> Any:
        seen.append(password)
        return make_cas()

    parse_cas_pdf(PDF, SecretStr("ABCPE1234F"), parser=parser)
    assert seen == ["ABCPE1234F"]


@pytest.mark.parametrize(
    ("exc", "error"),
    [
        (IncorrectPasswordError("Incorrect PDF password!"), WrongPasswordError),
        (CASParseError("Could not identify the CAS issuer."), UnrecognizedStatementError),
        (HeaderParseError("bad header"), UnrecognizedStatementError),
        (CASIntegrityError("ABCPE1234F folio 123 mismatch"), StatementParseError),
        (RuntimeError("pdfium: Failed to load document (PDF password)"), WrongPasswordError),
        (RuntimeError("something exploded"), StatementParseError),
        (ValueError("bad"), StatementParseError),
    ],
)
def test_parser_errors_are_mapped(exc: Exception, error: type[IngestError]) -> None:
    with pytest.raises(error) as info:
        parse_cas_pdf(PDF, "pw", parser=raising(exc), sniffer=lambda d, p: "")
    # Parser messages may carry PII; they must never be surfaced.
    assert "ABCPE1234F" not in str(info.value)
    assert "folio 123" not in str(info.value)


def test_mf_central_is_detected_when_issuer_unknown() -> None:
    pdf = make_pdf("Consolidated Account Statement - MFCentral")
    with pytest.raises(MFCentralStatementError):
        parse_cas_pdf(pdf, "", parser=raising(CASParseError("Could not identify the CAS issuer.")))


def test_mf_central_detection_uses_the_injected_sniffer() -> None:
    with pytest.raises(MFCentralStatementError):
        parse_cas_pdf(
            PDF, "", parser=raising(CASParseError("x")), sniffer=lambda d, p: "MF Central"
        )


def test_non_cas_pdf_with_real_casparser_is_unrecognised() -> None:
    """End to end through casparser itself with a PDF that is not a CAS."""
    with pytest.raises(UnrecognizedStatementError):
        parse_cas_pdf(make_pdf("Hello, this is not a statement"), "")


def test_real_casparser_detects_mf_central_pdf() -> None:
    with pytest.raises(MFCentralStatementError):
        parse_cas_pdf(make_pdf("MFCentral Consolidated Account Statement"), "")


@pytest.mark.parametrize(
    ("changes", "error"),
    [
        ({"cas_type": "SUMMARY"}, SummaryStatementError),
        ({"file_type": "NSDL"}, DepositoryStatementError),
        ({"file_type": "UNKNOWN"}, UnrecognizedStatementError),
    ],
)
def test_statement_type_errors_propagate(
    make_cas: MakeCas, changes: dict[str, str], error: type[IngestError]
) -> None:
    cas = make_cas()
    cas.update(changes)
    with pytest.raises(error):
        parse_cas_pdf(PDF, "pw", parser=returning(cas))


@pytest.mark.parametrize("result", [None, "text", 42, ["list"]])
def test_non_dict_parser_output_is_rejected(result: Any) -> None:
    with pytest.raises(StatementParseError):
        parse_cas_pdf(PDF, "pw", parser=returning(result))


def test_guard_runs_before_the_parser() -> None:
    called = False

    def parser(stream: io.BytesIO, password: str) -> Any:
        nonlocal called
        called = True

    with pytest.raises(NotAPdfError):
        parse_cas_pdf(b"not a pdf", "pw", parser=parser)
    assert not called


def test_bytearray_buffer_is_zeroed_after_success(make_cas: MakeCas) -> None:
    buf = bytearray(PDF)
    parse_cas_pdf(buf, "pw", parser=returning(make_cas()))
    assert buf == bytearray(len(PDF))


def test_bytearray_buffer_is_zeroed_after_failure() -> None:
    buf = bytearray(PDF)
    with pytest.raises(WrongPasswordError):
        parse_cas_pdf(buf, "pw", parser=raising(IncorrectPasswordError("x")))
    assert not any(buf)


# ---------- error catalogue ----------


@pytest.mark.parametrize("error", ALL_ERRORS)
def test_every_error_has_a_code_and_plain_message(error: type[IngestError]) -> None:
    assert error.code != IngestError.code
    assert 20 <= len(error.user_message) <= 300
    assert str(error()) == error.user_message


def test_error_codes_are_unique() -> None:
    codes = [e.code for e in ALL_ERRORS]
    assert len(codes) == len(set(codes))


def test_error_detail_overrides_str_but_not_user_message() -> None:
    err = StatementParseError("KeyError")
    assert str(err) == "KeyError"
    assert err.user_message.startswith("We recognised")
