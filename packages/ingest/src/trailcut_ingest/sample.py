"""The synthetic sample portfolio behind "Try a sample portfolio".

All funds, NAVs and identifiers are fictional (generated by
``scripts/make_sample.py``). It goes through the same normalizer as a real
statement, so the demo exercises the real pipeline.

Example:
    >>> p = load_sample_portfolio()
    >>> p.source.value, len(p.schemes)
    ('sample', 6)
"""

from __future__ import annotations

import json
from functools import cache
from importlib.resources import files
from typing import Any

from trailcut_engine.portfolio import Portfolio, StatementSource
from trailcut_ingest.normalize import normalize_cas

SAMPLE_RESOURCE = "samples/sample_cas.json"


def sample_cas_dict() -> dict[str, Any]:
    """The raw casparser-shaped sample statement."""
    text = files("trailcut_ingest").joinpath(SAMPLE_RESOURCE).read_text(encoding="utf-8")
    data: dict[str, Any] = json.loads(text)
    return data


@cache
def load_sample_portfolio() -> Portfolio:
    """The normalized sample portfolio (cached; models are immutable)."""
    return normalize_cas(sample_cas_dict(), source=StatementSource.SAMPLE)
