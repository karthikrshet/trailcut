import { BladeProvider } from '@razorpay/blade/components';
import { bladeTheme } from '@razorpay/blade/tokens';
import { render, type RenderResult } from '@testing-library/react';
import { MotionConfig } from 'motion/react';
import type { ReactElement } from 'react';

import type { SessionResponse } from '../api/types';
import fixture from './fixtures/session.json';

/** Render inside BladeProvider, as the app does. */
export function renderUi(ui: ReactElement, { reducedMotion = false } = {}): RenderResult {
  return render(
    <BladeProvider themeTokens={bladeTheme} colorScheme="light">
      <MotionConfig reducedMotion={reducedMotion ? 'always' : 'never'}>{ui}</MotionConfig>
    </BladeProvider>,
  );
}

/** A deep copy of the real API sample session (generated by scripts/make_web_fixture.py). */
export function sampleSession(): SessionResponse {
  return structuredClone(fixture) as SessionResponse;
}

/** Make `prefers-reduced-motion: reduce` match (or not) for the next render. */
export function setReducedMotion(reduce: boolean): void {
  Object.defineProperty(window, 'matchMedia', {
    writable: true,
    value: (query: string) => ({
      matches: reduce && query.includes('prefers-reduced-motion'),
      media: query,
      onchange: null,
      addListener: () => undefined,
      removeListener: () => undefined,
      addEventListener: () => undefined,
      removeEventListener: () => undefined,
      dispatchEvent: () => false,
    }),
  });
}
